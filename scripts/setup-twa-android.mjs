/**
 * Build the Chrome-backed Android variant from the existing Capacitor shell.
 * This never edits the actual site's Firebase configuration or visual layout.
 *
 * NEVOFOCUS_TWA_URL must be the *real* HTTPS origin at which PWA login works.
 * --ci-smoke uses the invalid .invalid test domain strictly to compile code;
 * the resulting APK is not a usable app and MUST NOT be distributed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const smoke = process.argv.includes('--ci-smoke');
// Explicit opt-in private APK variant; the default build keeps the current Android target.
const legacyCapsule = process.env.NEVOFOCUS_LEGACY_CAPSULE === '1';
const raw = process.env.NEVOFOCUS_TWA_URL || (smoke ? 'https://nevofocus.invalid/' : '');

if (!raw) {
  throw new Error('Missing NEVOFOCUS_TWA_URL: provide the working HTTPS URL of the live NevoFocus PWA.');
}

const start = new URL(raw);
if (start.protocol !== 'https:' || !start.hostname ||
    start.username || start.password || start.hash ||
    (!smoke && (start.hostname.endsWith('.invalid') || start.hostname === 'example.com'))) {
  throw new Error('NEVOFOCUS_TWA_URL must be a real public HTTPS URL, not a placeholder or local address.');
}
const nativeMain = path.join(root, 'native', 'android-twa', 'app', 'src', 'main');
const androidMain = path.join(root, 'android', 'app', 'src', 'main');
const targetJava = path.join(androidMain, 'java', 'com', 'furknsss', 'nevofocus');
const manifestPath = path.join(androidMain, 'AndroidManifest.xml');
const appGradlePath = path.join(root, 'android', 'app', 'build.gradle');
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';

execFileSync(npm, ['run', 'android:setup'], { cwd: root, stdio: 'inherit' });
fs.cpSync(nativeMain, androidMain, { recursive: true, force: true });
const nativeTest = path.join(root, 'native', 'android-twa', 'app', 'src', 'test');
if (fs.existsSync(nativeTest)) {
  fs.cpSync(nativeTest, path.join(root, 'android', 'app', 'src', 'test'),
    { recursive: true, force: true });
}
// Remove Capacitor's generated example tests, whose package assertion targets
// the template app rather than NevoFocus. Keep our native regression suites.
fs.rmSync(path.join(root, 'android', 'app', 'src', 'androidTest', 'java', 'com', 'getcapacitor', 'myapp'),
  { recursive: true, force: true });
const nativeDeviceTest = path.join(root, 'native', 'android-twa', 'app', 'src', 'androidTest');
if (fs.existsSync(nativeDeviceTest)) {
  fs.cpSync(nativeDeviceTest, path.join(root, 'android', 'app', 'src', 'androidTest'),
    { recursive: true, force: true });
}
fs.mkdirSync(targetJava, { recursive: true });
const webConfig = `package com.furknsss.nevofocus;

// Generated by scripts/setup-twa-android.mjs: do not edit by hand.
public final class TwaWebConfig {
    private TwaWebConfig() {}
    public static final String ORIGIN = ${JSON.stringify(start.origin)};
    public static final String START_URL = ${JSON.stringify(start.toString())};
}
`;
fs.writeFileSync(path.join(targetJava, 'TwaWebConfig.java'), webConfig);

let manifest = fs.readFileSync(manifestPath, 'utf8');
if (!manifest.includes('android:name="androidx.browser.customtabs.PostMessageService"')) {
  const service = `
        <service
            android:name="androidx.browser.customtabs.PostMessageService"
            android:exported="true" />
`;
  if (!manifest.includes('</application>')) throw new Error('Capacitor AndroidManifest.xml missing application.');
  manifest = manifest.replace('</application>', service + '    </application>');
}
if (!manifest.includes('android.support.customtabs.action.CustomTabsService')) {
  const queries = `
    <queries>
        <intent>
            <action android:name="android.support.customtabs.action.CustomTabsService" />
        </intent>
    </queries>
`;
  if (!manifest.includes('<application')) throw new Error('Capacitor AndroidManifest.xml missing application.');
  manifest = manifest.replace(/<application\b/, queries + '    <application');
}
// Use the same app package as the original test build.
fs.writeFileSync(manifestPath, manifest);

let gradle = fs.readFileSync(appGradlePath, 'utf8');
const dependency = 'implementation "androidx.browser:browser:1.10.0"';
const junitDependency = 'testImplementation "junit:junit:4.13.2"';
const instrumentationDependency = 'androidTestImplementation "androidx.test:runner:1.6.2"';
const instrumentationJunitDependency = 'androidTestImplementation "androidx.test.ext:junit:1.2.1"';
const uiAutomatorDependency = 'androidTestImplementation "androidx.test.uiautomator:uiautomator:2.3.0"';
if (!gradle.includes(dependency)) {
  if (!gradle.includes('dependencies {')) throw new Error('Android Gradle dependencies block not found.');
  gradle = gradle.replace('dependencies {', 'dependencies {\n    ' + dependency);
}
if (!gradle.includes(junitDependency)) {
  gradle = gradle.replace('dependencies {', 'dependencies {\n    ' + junitDependency);
}
for (const required of [instrumentationDependency, instrumentationJunitDependency, uiAutomatorDependency]) {
  if (!gradle.includes(required)) {
    gradle = gradle.replace('dependencies {', 'dependencies {\n    ' + required);
  }
}
// Add a real instrumentation runner without changing the existing app's
// package ID, minSdk, targetSdk, or build variant.
if (!gradle.includes('testInstrumentationRunner "androidx.test.runner.AndroidJUnitRunner"')) {
  const defaultConfigStart = gradle.indexOf('defaultConfig {');
  if (defaultConfigStart < 0) throw new Error('Android Gradle defaultConfig block missing.');
  gradle = gradle.slice(0, defaultConfigStart + 'defaultConfig {'.length) +
    '\n        testInstrumentationRunner "androidx.test.runner.AndroidJUnitRunner"' +
    gradle.slice(defaultConfigStart + 'defaultConfig {'.length);
}
// CI test builds must use an explicit reusable signing key. Relying on
// Gradle's machine-local debug.keystore produces a new SHA-256 on each run,
// permanently breaking the TWA site/app association.
if (process.env.NEVOFOCUS_TWA_SIGNING_STORE) {
  const store = path.resolve(process.env.NEVOFOCUS_TWA_SIGNING_STORE);
  if (!fs.existsSync(store)) {
    throw new Error('Configured TWA debug keystore is missing: ' + store);
  }
  if (!gradle.includes('android {')) throw new Error('Android Gradle android block not found.');
  gradle = gradle.replace('android {', `android {
    signingConfigs {
        debug {
            storeFile file(${JSON.stringify(store)})
            storePassword "android"
            keyAlias "androiddebugkey"
            keyPassword "android"
        }
    }`);
}
const targetPattern = /\btargetSdk(?:Version)?\s*(?:=\s*)?(?:rootProject\.ext\.targetSdkVersion|\d+)/;
if (!targetPattern.test(gradle)) throw new Error('Generated Android targetSdk declaration missing.');
gradle = gradle.replace(targetPattern, legacyCapsule
  ? 'targetSdkVersion 30'
  : 'targetSdkVersion rootProject.ext.targetSdkVersion');
gradle = gradle.replace(/\bversionCode\s+\d+/, 'versionCode 9')
  .replace(/\bversionName\s+"[^"]+"/, 'versionName "' +
    (legacyCapsule ? '1.2.4-premium-capsule' : '1.2.4-focus-notification') + '"');
fs.writeFileSync(appGradlePath, gradle);

// Keep layout dimensions literal: SystemUI inflates RemoteViews in a different
// process, and dimension resource indirection crashed the compact capsule on
// Android 15. Only the explicit compatibility build expands the normal 48/34dp
// layout to 64/44dp. Regular builds preserve the modern OS limits.
if (legacyCapsule) {
  const capsulePath = path.join(androidMain, 'res', 'layout', 'nevofocus_live_notification.xml');
  let capsule = fs.readFileSync(capsulePath, 'utf8');
  const expected = ['android:layout_height="48dp"', 'android:layout_width="34dp"',
    'android:layout_height="34dp"'];
  for (const token of expected) {
    if (!capsule.includes(token)) throw new Error('Missing capsule layout dimension: ' + token);
  }
  capsule = capsule.replace('android:layout_height="48dp"', 'android:layout_height="64dp"')
    .replaceAll('android:layout_width="34dp"', 'android:layout_width="44dp"')
    .replaceAll('android:layout_height="34dp"', 'android:layout_height="44dp"');
  fs.writeFileSync(capsulePath, capsule);
}

// GitHub shared runners can receive Maven Central HTTP 429 after repeated
// Android CI builds. Prefer Google's public Maven Central mirror with the
// official Maven Central repository retained as a fallback.
const rootGradleFile = path.join(root, 'android', 'build.gradle');
const rootGradle = fs.readFileSync(rootGradleFile, 'utf8');
const googleMavenMirror = 'maven { url "https://maven-central.storage-download.googleapis.com/maven2/" }';
if (!rootGradle.includes(googleMavenMirror)) {
  if (!rootGradle.includes('mavenCentral()')) {
    throw new Error('Generated Android build.gradle has no mavenCentral() repository.');
  }
  fs.writeFileSync(rootGradleFile,
    rootGradle.replaceAll('mavenCentral()', googleMavenMirror + '\n        mavenCentral()'));
}

console.log('Chrome-backed NevoFocus TWA Android variant prepared.');
console.log('Verified-origin configured: ' + start.origin);
if (smoke) {
  console.warn('CI SMOKE BUILD ONLY. THIS BUILD IS NOT A FUNCTIONAL APP.');
} else {
  console.log('Publish .well-known/assetlinks.json at this HTTPS origin before device testing.');
}

